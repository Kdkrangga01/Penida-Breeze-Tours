/**
 * Cari destinasi berdasarkan slug
 * @param {string} slug
 * @returns {object|undefined}
 */
export function getDestinationBySlug(slug) {
  if (!slug) return undefined;
  return destinations.find((d) => d.slug === slug || d.altSlug === slug);
}

/**
 * Ambil destinasi berdasarkan kategori
 * @param {'west'|'east'|'all'} category
 * @returns {object[]}
 */
export function getDestinationsByCategory(category) {
  if (category === 'all') return destinations;
  return destinations.filter((d) => d.category === category);
}
